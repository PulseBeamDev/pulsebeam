// Pinned ba469aa stats object fields. Included after the typed field converters.
inline std::uint8_t StatsClass(const webrtc::RTCStats& s) {
  if (s.type() == webrtc::RTCCertificateStats::kType) return 1;
  if (s.type() == webrtc::RTCCodecStats::kType) return 2;
  if (s.type() == webrtc::RTCDataChannelStats::kType) return 3;
  if (s.type() == webrtc::RTCIceCandidatePairStats::kType) return 4;
  if (s.type() == webrtc::RTCIceCandidateStats::kType) return 5;
  if (s.type() == webrtc::RTCLocalIceCandidateStats::kType) return 6;
  if (s.type() == webrtc::RTCRemoteIceCandidateStats::kType) return 7;
  if (s.type() == webrtc::RTCPeerConnectionStats::kType) return 8;
  if (s.type() == webrtc::RTCRtpStreamStats::kType) return 9;
  if (s.type() == webrtc::RTCReceivedRtpStreamStats::kType) return 10;
  if (s.type() == webrtc::RTCSentRtpStreamStats::kType) return 11;
  if (s.type() == webrtc::RTCInboundRtpStreamStats::kType) return 12;
  if (s.type() == webrtc::RTCOutboundRtpStreamStats::kType) return 13;
  if (s.type() == webrtc::RTCRemoteInboundRtpStreamStats::kType) return 14;
  if (s.type() == webrtc::RTCRemoteOutboundRtpStreamStats::kType) return 15;
  if (s.type() == webrtc::RTCMediaSourceStats::kType) return 16;
  if (s.type() == webrtc::RTCAudioSourceStats::kType) return 17;
  if (s.type() == webrtc::RTCVideoSourceStats::kType) return 18;
  if (s.type() == webrtc::RTCTransportStats::kType) return 19;
  if (s.type() == webrtc::RTCAudioPlayoutStats::kType) return 20;
  return 0;
}
inline std::unique_ptr<webrtc::RTCStats> NewStats(std::uint8_t kind, const std::string& id, webrtc::Timestamp timestamp) {
  switch (kind) {
    case 1: return std::make_unique<webrtc::RTCCertificateStats>(id, timestamp);
    case 2: return std::make_unique<webrtc::RTCCodecStats>(id, timestamp);
    case 3: return std::make_unique<webrtc::RTCDataChannelStats>(id, timestamp);
    case 4: return std::make_unique<webrtc::RTCIceCandidatePairStats>(id, timestamp);
    case 6: return std::make_unique<webrtc::RTCLocalIceCandidateStats>(id, timestamp);
    case 7: return std::make_unique<webrtc::RTCRemoteIceCandidateStats>(id, timestamp);
    case 8: return std::make_unique<webrtc::RTCPeerConnectionStats>(id, timestamp);
    case 12: return std::make_unique<webrtc::RTCInboundRtpStreamStats>(id, timestamp);
    case 13: return std::make_unique<webrtc::RTCOutboundRtpStreamStats>(id, timestamp);
    case 14: return std::make_unique<webrtc::RTCRemoteInboundRtpStreamStats>(id, timestamp);
    case 15: return std::make_unique<webrtc::RTCRemoteOutboundRtpStreamStats>(id, timestamp);
    case 17: return std::make_unique<webrtc::RTCAudioSourceStats>(id, timestamp);
    case 18: return std::make_unique<webrtc::RTCVideoSourceStats>(id, timestamp);
    case 19: return std::make_unique<webrtc::RTCTransportStats>(id, timestamp);
    case 20: return std::make_unique<webrtc::RTCAudioPlayoutStats>(id, timestamp);
    default: return nullptr; // Protected base constructors are not public SDK constructors.
  }
}
