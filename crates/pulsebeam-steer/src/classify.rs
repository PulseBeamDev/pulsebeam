//! Bounds-checked client bootstrap classification, independent of admission.

use crate::stun;
use crate::ufrag::{self, UfragError};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DropReason {
    NoUsername,
    BadUfragLen,
    BadUfragEncoding,
    BadVersion,
    WrongCluster,
    WrongNode,
    InvalidShard,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NodeScope {
    pub cluster_id: u16,
    pub node_id: u16,
    pub shard_count: u16,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Bootstrap {
    NotStun,
    /// A candidate only. The caller must validate live ownership, epoch and ICE.
    Route {
        shard: u16,
        slot: u32,
        epoch: u16,
    },
    Reject(DropReason),
}

/// Classifies a UDP payload without creating a flow or authenticating ICE.
/// Non-STUN bytes are left to the caller's established-flow handling.
pub fn classify_bootstrap(payload: &[u8], scope: NodeScope) -> Bootstrap {
    if !stun::is_stun(payload) {
        return Bootstrap::NotStun;
    }
    let Some(username) = stun::server_ufrag(payload) else {
        return Bootstrap::Reject(DropReason::NoUsername);
    };
    let u = match decode_ufrag_token(username) {
        Ok(u) => u,
        Err(reason) => return Bootstrap::Reject(reason),
    };
    if u.cluster_id() != scope.cluster_id {
        return Bootstrap::Reject(DropReason::WrongCluster);
    }
    if u.node_id() != scope.node_id {
        return Bootstrap::Reject(DropReason::WrongNode);
    }
    if u.transport().shard() >= scope.shard_count {
        return Bootstrap::Reject(DropReason::InvalidShard);
    }
    Bootstrap::Route {
        shard: u.transport().shard(),
        slot: u.transport().slot(),
        epoch: u.epoch(),
    }
}

fn decode_ufrag_token(token: &[u8]) -> Result<ufrag::IceUfrag, DropReason> {
    if token.len() != ufrag::ENCODED_LEN {
        return Err(DropReason::BadUfragLen);
    }
    ufrag::decode_ascii_detailed(token).map_err(|e| match e {
        UfragError::BadEncoding => DropReason::BadUfragEncoding,
        UfragError::BadVersion => DropReason::BadVersion,
        UfragError::InvalidCluster => DropReason::WrongCluster,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::vec::Vec;

    const SCOPE: NodeScope = NodeScope {
        cluster_id: 0xABC,
        node_id: 0x1234,
        shard_count: 8,
    };

    fn packet(token: &[u8]) -> Vec<u8> {
        let mut buf = Vec::from([0x00, 0x01, 0, 0, 0x21, 0x12, 0xA4, 0x42]);
        buf.resize(20, 0);
        let mut username = Vec::from(token);
        username.extend_from_slice(b":client");
        let padded = (username.len() + 3) & !3;
        buf.extend_from_slice(&[0, 6]);
        buf.extend_from_slice(&u16::try_from(username.len()).unwrap().to_be_bytes());
        buf.extend_from_slice(&username);
        buf.resize(24 + padded, 0);
        buf[2..4].copy_from_slice(&u16::try_from(4 + padded).unwrap().to_be_bytes());
        buf
    }

    #[test]
    fn legacy_wire_fixture_and_node_scope() {
        // Independently pinned v0 bytes, not generated by the codec under test.
        let buf = packet(b"1AY14D00E0R3J01A");
        assert_eq!(
            classify_bootstrap(&buf, SCOPE),
            Bootstrap::Route {
                shard: 7,
                slot: 12345,
                epoch: 42
            }
        );
        for (scope, reason) in [
            (
                NodeScope {
                    cluster_id: 1,
                    ..SCOPE
                },
                DropReason::WrongCluster,
            ),
            (
                NodeScope {
                    node_id: 1,
                    ..SCOPE
                },
                DropReason::WrongNode,
            ),
            (
                NodeScope {
                    shard_count: 7,
                    ..SCOPE
                },
                DropReason::InvalidShard,
            ),
            (
                NodeScope {
                    shard_count: 0,
                    ..SCOPE
                },
                DropReason::InvalidShard,
            ),
        ] {
            assert_eq!(classify_bootstrap(&buf, scope), Bootstrap::Reject(reason));
        }
        // A trailing datagram suffix does not change declared-message parsing.
        let mut with_suffix = buf.clone();
        with_suffix.extend_from_slice(b"ignored");
        assert_eq!(
            classify_bootstrap(&with_suffix, SCOPE),
            classify_bootstrap(&buf, SCOPE)
        );
        for len in 20..buf.len() {
            assert_eq!(
                classify_bootstrap(&buf[..len], SCOPE),
                Bootstrap::Reject(DropReason::NoUsername)
            );
        }
    }

    #[test]
    fn invalid_bootstrap_and_non_stun_remain_distinct() {
        assert_eq!(classify_bootstrap(b"media", SCOPE), Bootstrap::NotStun);
        for (token, reason) in [
            (b"short".as_slice(), DropReason::BadUfragLen),
            (b"UAY14D00E0R3J01A".as_slice(), DropReason::BadUfragEncoding),
            (b"3AY14D00E0R3J01A".as_slice(), DropReason::BadVersion),
        ] {
            assert_eq!(
                classify_bootstrap(&packet(token), SCOPE),
                Bootstrap::Reject(reason)
            );
        }
        let mut buf = packet(b"1AY14D00E0R3J01A");
        buf[20..22].copy_from_slice(&[0, 0x24]);
        assert_eq!(
            classify_bootstrap(&buf, SCOPE),
            Bootstrap::Reject(DropReason::NoUsername)
        );
    }

    #[test]
    fn hostile_bytes_and_attribute_lengths_are_bounded_and_panic_free() {
        let mut state = 0x243F_6A88_85A3_08D3u64;
        let mut bytes = [0u8; 1024];
        for len in 0..=bytes.len() {
            for b in &mut bytes[..len] {
                state = state.wrapping_mul(6364136223846793005).wrapping_add(1);
                *b = (state >> 32) as u8;
            }
            let _ = classify_bootstrap(&bytes[..len], SCOPE);
        }
        // Sweep every possible declared length against a fixed truncated packet.
        let mut buf = packet(b"1AY14D00E0R3J01A");
        for length in 0..=u16::MAX {
            buf[2..4].copy_from_slice(&length.to_be_bytes());
            let _ = classify_bootstrap(&buf, SCOPE);
            buf[22..24].copy_from_slice(&length.to_be_bytes());
            let _ = classify_bootstrap(&buf, SCOPE);
        }
        // Maximum-sized traversal with no USERNAME, including a trailing partial header.
        let mut maximum = std::vec![0; 20 + usize::from(u16::MAX)];
        maximum[..8].copy_from_slice(&[0, 1, 0xFF, 0xFF, 0x21, 0x12, 0xA4, 0x42]);
        assert_eq!(
            classify_bootstrap(&maximum, SCOPE),
            Bootstrap::Reject(DropReason::NoUsername)
        );
    }
}
