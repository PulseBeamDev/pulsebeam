pub const NATIVE_QUIC_INITIAL_CID_BYTES: usize = 20;

/// An advertised TLS DNS authority, not an IP literal or a host-and-port pair.
pub fn valid_native_quic_host(value: &str) -> bool {
    let host = value.strip_suffix('.').unwrap_or(value);
    host.len() <= 253
        && host
            .rsplit('.')
            .next()
            .is_some_and(|label| label.bytes().any(|b| b.is_ascii_alphabetic()))
        && host.split('.').all(|label| {
            (1..=63).contains(&label.len())
                && !label.starts_with('-')
                && !label.ends_with('-')
                && label
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-')
        })
}

