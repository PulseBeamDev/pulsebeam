import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const [source, output] = process.argv.slice(2);
if (!source || !output)
  throw new Error("Expected WASM input and JavaScript output paths");
const bytes = readFileSync(source);
if (bytes.length > 8 * 1024 * 1024)
  throw new RangeError(
    "WASM artifact exceeds Chromium's 8 MiB synchronous compilation limit",
  );
const encoded = bytes.toString("base64");
mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/wasm-bytes.mjs.
let encoded = ${JSON.stringify(encoded)};
let compiled;

export function wasmModule() {
  if (compiled === undefined) {
    const decoded = atob(encoded);
    const bytes = new Uint8Array(decoded.length);
    for (let index = 0; index < decoded.length; index++) {
      bytes[index] = decoded.charCodeAt(index);
    }
    compiled = new WebAssembly.Module(bytes);
    encoded = "";
  }
  return compiled;
}
`,
);
