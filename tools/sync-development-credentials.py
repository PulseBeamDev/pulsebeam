#!/usr/bin/env python3
"""Sync packaged development credentials from the canonical JSON fixture.

Run: python tools/sync-development-credentials.py
Check: python tools/sync-development-credentials.py --check
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).absolute().parent.parent
SOURCE = ROOT / "server/auth/development.json"
COPIES = (
    "server/go/development.json",
    "server/rust/src/development.json",
    "server/python/pulsebeam_server/development.json",
    "server/typescript/src/development.json",
)
ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def decoded(value, prefix, length, skip_bits=0):
    assert value.startswith(prefix)
    digits = value[len(prefix):]
    number = 0
    for digit in digits:
        number = (number << 5) | ALPHABET.index(digit)
    total_bits = len(digits) * 5
    assert number >> (total_bits - skip_bits) == 0
    return ((number >> (total_bits - skip_bits - length * 8)) &
            ((1 << (length * 8)) - 1)).to_bytes(length, "big")


def bytes_literal(value):
    return ", ".join(f"0x{x:02x}" for x in value)


def id_literal(value):
    return ", ".join(f"0x{x:02x}" if x in (0x70, 0x80) else str(x) for x in value)


def rust_constants(credentials):
    project = decoded(credentials["projectId"], "p_0", 16)
    key = decoded(credentials["keyId"], "kid_0", 16)
    signing = decoded(credentials["secret"], "sk_0", 32, 4)
    verify = decoded(credentials["publicKey"], "pk_0", 32, 4)
    return (
        "// @generated by tools/sync-development-credentials.py; do not edit.\n"
        "use crate::identity::{ApiKeyId, ProjectId};\n"
        "use pulsebeam_auth::keys::{ApiSigningKey, ApiVerifyingKey};\n\n"
        "pub const DEVELOPMENT_PROJECT_ID: ProjectId =\n"
        f"    ProjectId::from_bytes([{id_literal(project)}]);\n"
        "pub const DEVELOPMENT_API_KEY_ID: ApiKeyId =\n"
        f"    ApiKeyId::from_bytes([{id_literal(key)}]);\n"
        "pub const DEVELOPMENT_API_SIGNING_KEY: ApiSigningKey = ApiSigningKey::from_seed([\n"
        f"    {bytes_literal(signing[:16])},\n"
        f"    {bytes_literal(signing[16:])},\n"
        "]);\n"
        "pub const DEVELOPMENT_API_VERIFYING_KEY: ApiVerifyingKey = ApiVerifyingKey::from_bytes_unchecked([\n"
        f"    {bytes_literal(verify[:16])},\n"
        f"    {bytes_literal(verify[16:])},\n"
        "]);\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = SOURCE.read_text()
    fixture = json.loads(source)
    destinations = {path: source for path in COPIES}
    destinations["crates/pulsebeam-core/src/development.rs"] = rust_constants(fixture)
    stale = []
    for relative, expected in destinations.items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != expected:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if stale:
        parser.error("regenerate development credentials: " + ", ".join(stale))


if __name__ == "__main__":
    main()
